#Utilizar entradas en operaciones
print("-------------------")
print("    CALCULADORA    ")
print("-------------------")
a = int(input("Escribe el primer numero"))
b = int(input("Escribe el segundo numero"))

print("Resultados:")
print(f"Suma: {a + b}")
print(f"Resta: {a - b}")
print(f"Multiplicación: {a * b}")
print(f"División: {a / b}")
print(f"División entera: {a // b}")
print(f"Residuo: {a % b}")